// Centrage par défaut si l'utilisateur n'a pas renseigné de pays de résidence (ou que ce
// pays n'est pas dans la liste) : Séoul, cœur historique des lieux du site.
window.DEFAULT_MAP_CENTER = [37.541, 127.025, 6];

window.getMapCenterForCountry = function (countryName) {
    if (countryName && window.COUNTRY_CENTERS[countryName]) return window.COUNTRY_CENTERS[countryName];
    return window.DEFAULT_MAP_CENTER;
};

// Génère les <option> du sélecteur de pays (utilisé sur index.html, étape "Profile").
window.populateCountrySelect = function (selectId) {
    const select = document.getElementById(selectId);
    if (!select) return;
    const countries = Object.keys(window.COUNTRY_CENTERS).sort((a, b) => a.localeCompare(b));
    countries.forEach(name => {
        const opt = document.createElement('option');
        opt.value = name;
        opt.textContent = name;
        select.appendChild(opt);
    });
};
